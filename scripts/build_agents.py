"""Generate the per-tool agent files from the shared role files.

Reads agents/roles/<role>.md and writes:
  agents/claude-code/<role>.md  (Claude Code subagent)
  agents/codex/<role>.toml      (Codex custom agent)

Run from anywhere: python scripts/build_agents.py
Uses only the Python standard library.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROLES_DIR = ROOT / "agents" / "roles"
CLAUDE_DIR = ROOT / "agents" / "claude-code"
CODEX_DIR = ROOT / "agents" / "codex"

# Claude Code model alias for each tier.
CLAUDE_MODELS = {"strongest": "opus", "middle": "sonnet", "fast": "haiku"}

# Codex has one example model; the tiers differ by reasoning effort.
CODEX_MODEL = "gpt-6.1-sol"
CODEX_EFFORT = {"strongest": "xhigh", "middle": "medium", "fast": "low"}

# Claude Code tools for a read-only role: no tools that write files.
CLAUDE_READ_ONLY_TOOLS = "Read, Grep, Glob, Bash, PowerShell, WebFetch, WebSearch"

REQUIRED = ("name", "description", "tier", "read_only")


def read_role(path):
    """Return (fields, instructions) from a role file."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"{path}: must start with a --- header")
    header, sep, body = text[4:].partition("\n---\n")
    if not sep:
        raise ValueError(f"{path}: header has no closing ---")
    fields = {}
    for line in header.splitlines():
        if line.strip():
            key, _, value = line.partition(":")
            fields[key.strip()] = value.strip()
    for key in REQUIRED:
        if key not in fields:
            raise ValueError(f"{path}: missing {key}")
    if fields["name"] != path.stem:
        raise ValueError(f"{path}: name must match the file name")
    if fields["tier"] not in CLAUDE_MODELS:
        raise ValueError(f"{path}: tier must be one of {', '.join(CLAUDE_MODELS)}")
    if fields["read_only"] not in ("yes", "no"):
        raise ValueError(f"{path}: read_only must be yes or no")
    return fields, body.strip() + "\n"


def quote(value):
    # A JSON string is also a valid YAML double-quoted scalar and a valid
    # TOML basic string.
    return json.dumps(value, ensure_ascii=False)


def toml_multiline(text):
    """Return text as a TOML multi-line basic string."""
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch in "\n\t":
            out.append(ch)
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append(f"\\u{ord(ch):04X}")
        else:
            out.append(ch)
    return '"""\n' + "".join(out) + '"""'


def claude_agent(role, fields, body):
    name = fields.get("claude_code_name", fields["name"])
    lines = [
        "---",
        f"# Generated by scripts/build_agents.py from agents/roles/{role}.md. Do not edit by hand.",
    ]
    if name != fields["name"]:
        lines.append(
            f"# The name is {name}, not {fields['name']}, so that this agent replaces"
            f" Claude Code's built-in {name} agent."
        )
    lines += [
        f"name: {name}",
        f"description: {quote(fields['description'])}",
        f"model: {CLAUDE_MODELS[fields['tier']]}",
    ]
    if fields["read_only"] == "yes":
        lines.append(f"tools: {CLAUDE_READ_ONLY_TOOLS}")
    lines += ["---", "", body]
    return "\n".join(lines)


def codex_agent(role, fields, body):
    lines = [
        f"# Generated by scripts/build_agents.py from agents/roles/{role}.md. Do not edit by hand.",
        "# Replace the model with one your account can use.",
    ]
    if fields["read_only"] == "yes":
        lines.append(
            "# A Codex agent file cannot set sandbox_mode, so the instructions keep it read-only."
        )
    lines += [
        f"name = {quote(fields['name'])}",
        f"description = {quote(fields['description'])}",
        f"model = {quote(CODEX_MODEL)}",
        f"model_reasoning_effort = {quote(CODEX_EFFORT[fields['tier']])}",
        f"developer_instructions = {toml_multiline(body)}",
        "",
    ]
    return "\n".join(lines)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(path.relative_to(ROOT).as_posix())


def main():
    roles = sorted(ROLES_DIR.glob("*.md"))
    if not roles:
        raise SystemExit(f"No role files in {ROLES_DIR}")
    for path in roles:
        fields, body = read_role(path)
        role = path.stem
        write(CLAUDE_DIR / f"{role}.md", claude_agent(role, fields, body))
        write(CODEX_DIR / f"{role}.toml", codex_agent(role, fields, body))


if __name__ == "__main__":
    main()
